/*
 * Regenerates src/shared/i18n/locales.ts from the language folders found in
 * src/shared/i18n/locales/: every folder is a language (it, en, fr…), every
 * JSON file inside it is a namespace. Run it after adding a language or a
 * namespace; `npm run dist` runs it too.
 *
 *   node tools/generate-locales-index.mjs
 *
 * Italian (`it`) is the reference language: the namespaces are the ones it
 * has. Another language may lack some of them (its texts then fall back to
 * English and Italian), but may not add namespaces that Italian lacks.
 */
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const localesDir = join(root, 'src', 'shared', 'i18n', 'locales')
const languages = readdirSync(localesDir)
  .filter((d) => statSync(join(localesDir, d)).isDirectory() && /^[a-z]{2,3}(-[A-Z]{2})?$/.test(d))
  .sort((a, b) => (a === 'it' ? -1 : b === 'it' ? 1 : a.localeCompare(b)))
if (!languages.includes('it')) throw new Error('The reference language folder locales/it is missing.')

const namespacesOf = (lang) =>
  readdirSync(join(localesDir, lang))
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -5))
    .sort()
const reference = namespacesOf('it')

const ident = (ns, lang) => ns.replace(/[^A-Za-z0-9]/g, '_') + '_' + lang.replace(/[^A-Za-z0-9]/g, '_')
const lines = [
  '/**',
  ' * Language files, one folder per language and one JSON per area of the',
  ' * program (namespace). Generated by `tools/generate-locales-index.mjs`',
  ' * from the folders under locales/: do not edit by hand.',
  ' */'
]
const present = {}
for (const lang of languages) {
  const own = new Set(namespacesOf(lang))
  const extra = [...own].filter((ns) => !reference.includes(ns))
  if (extra.length) throw new Error(`locales/${lang} has namespaces that Italian lacks: ${extra.join(', ')}`)
  present[lang] = reference.filter((ns) => own.has(ns))
  for (const ns of present[lang]) lines.push(`import ${ident(ns, lang)} from './locales/${lang}/${ns}.json'`)
}
lines.push('', 'export const LOCALES = {')
languages.forEach((lang, i) => {
  lines.push(`  ${JSON.stringify(lang)}: {`)
  present[lang].forEach((ns, j) => lines.push(`    ${JSON.stringify(ns)}: ${ident(ns, lang)}${j < present[lang].length - 1 ? ',' : ''}`))
  lines.push(`  }${i < languages.length - 1 ? ',' : ''}`)
})
lines.push('} as const', '')
writeFileSync(join(root, 'src', 'shared', 'i18n', 'locales.ts'), lines.join('\n'), 'utf8')
console.log('Languages: ' + languages.join(', ') + ' · namespaces: ' + reference.length)
for (const lang of languages) if (present[lang].length < reference.length) console.log(`  ${lang}: ${reference.length - present[lang].length} namespaces missing (fallback to English/Italian)`)
